import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { z } from "zod";
import { loadVerifications } from "../tools/reporters/verifications.ts";

/**
 * QA-1 / FB-4 evidence, in the repo while Linear is not reachable: for every verification line, the
 * tests that prove it (from the last `pnpm check` run), their state, and any screenshots.
 *   node scripts/evidence-report.ts   → evidence/REPORT.md
 */
const ROOT = path.resolve(import.meta.dirname, "..");
const zRun = z.array(z.object({ ids: z.array(z.string()), test: z.string(), file: z.string(), state: z.string(), attachments: z.array(z.string()).optional() }));
const read = (f: string) => (existsSync(path.join(ROOT, "evidence", f)) ? zRun.parse(JSON.parse(readFileSync(path.join(ROOT, "evidence", f), "utf8"))) : []);
const runs = [...read("vitest.json").map((r) => ({ ...r, kind: "test" })), ...read("playwright.json").map((r) => ({ ...r, kind: "journey" }))];
const notes = z.record(z.string(), z.string()).parse(JSON.parse(readFileSync(path.join(ROOT, "evidence", "not-true.json"), "utf8")));
const manual = z.record(z.string(), z.string()).parse(JSON.parse(readFileSync(path.join(ROOT, "evidence", "manual.json"), "utf8")));
const ok = (s: string) => s === "passed" || s === "pass";

const out: string[] = ["# Verification evidence", "", "Generated by `node scripts/evidence-report.ts` from the last `pnpm check` run.", ""];
let proven = 0;
let open = 0;
const rows: string[] = [];
for (const [id, text] of loadVerifications()) {
  const mine = runs.filter((r) => r.ids.includes(id));
  const blocked = notes[id];
  const passing = (mine.length > 0 && mine.every((r) => ok(r.state))) || (mine.length === 0 && manual[id] !== undefined);
  const status = blocked !== undefined ? "NOT TRUE YET" : passing ? "proven" : mine.length === 0 ? "NO EVIDENCE" : "FAILING";
  if (status === "proven") proven += 1;
  else open += 1;
  rows.push(`## ${id} — ${status}`, "", `> ${text}`, "");
  if (blocked !== undefined) rows.push(`**Why not:** ${blocked}`, "");
  if (manual[id] !== undefined) rows.push(`**Run:** ${manual[id]}`, "");
  for (const r of mine) {
    rows.push(`- ${ok(r.state) ? "✅" : "❌"} ${r.kind}: \`${r.file}\` — ${r.test.replace(/\[[A-Z]{2,4}-\d{1,2}\]/g, "").trim()}`);
    for (const a of r.attachments ?? []) if (a.endsWith(".png")) rows.push(`  - screenshot: [${path.basename(a)}](${path.relative("evidence", a)})`);
  }
  rows.push("");
}
out.push(`**${proven} proven, ${open} not yet true.**`, "", ...rows);
writeFileSync(path.join(ROOT, "evidence", "REPORT.md"), out.join("\n"));
console.log(JSON.stringify({ proven, open }));
